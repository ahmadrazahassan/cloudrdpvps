/** "United Arab Emirates" → "united-arab-emirates": lower case, accents dropped, hyphens between words. Used for country addresses everywhere. */
export const slugify = (s: string) =>
  s
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 40);
